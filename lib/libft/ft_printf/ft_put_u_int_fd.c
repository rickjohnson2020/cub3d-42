#include "ft_printf.h"

void	ft_put_u_int_fd(unsigned int u, int fd)
{
	char	c;

	c = '0';
	if (u >= 10)
		ft_put_u_int_fd((u / 10), fd);
	c = c + (u % 10);
	ft_putchar_fd(c, fd);
}
